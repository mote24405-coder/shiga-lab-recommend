def expand_query(query: str, extra: dict[str, list[str]] | None = None) -> list[str]:
    """クエリを同義語で展開して検索キーワードのリストを返す。"""
    synonyms = {**DEFAULT_SYNONYMS, **(extra or {})}
    terms = {query}
    q_lower = query.lower()
    for key, vals in synonyms.items():
        if key.lower() == q_lower or q_lower in [v.lower() for v in vals]:
            terms.add(key)
            terms.update(vals)
    return list(terms)
