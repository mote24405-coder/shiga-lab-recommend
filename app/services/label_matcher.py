class LabelExtractor(ABC):
    @abstractmethod
    def extract(self, text: str, label_names: list[str]) -> list[str]:
        """テキストからラベル候補名のリストを返す。"""
        ...


class RuleBasedLabelExtractor(LabelExtractor):
    def extract(self, text: str, label_names: list[str]) -> list[str]:
        text_lower = text.lower()
        matched = []
        for label_name in label_names:
            keywords = LABEL_RULES.get(label_name, [label_name])
            if any(kw.lower() in text_lower for kw in keywords):
                matched.append(label_name)
        return matched


def get_label_extractor() -> LabelExtractor:
    return RuleBasedLabelExtractor()
